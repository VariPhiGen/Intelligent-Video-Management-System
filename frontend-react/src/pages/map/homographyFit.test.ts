/**
 * Tests for the client-side frame -> plan fit (homographyFit.ts).
 *
 * The backend has its own suite for judging a submitted matrix. These cover the
 * half that only exists here: turning clicked landmarks into one. The failure
 * that matters is not a thrown error — it is a fit that reports a small
 * reprojection error while describing the wrong view, so most of these check
 * recovery of a KNOWN transform rather than merely that a matrix came back.
 */
import { describe, expect, it } from 'vitest';

import {
  apply,
  fitHomography,
  MIN_PAIRS,
  perPairResidual,
  suspectPin,
  reprojectionRms,
  type Matrix3,
  type Pair,
} from './homographyFit';

/** A camera looking at the ground at an angle: non-zero third row, so the far
 *  half of the frame compresses and a horizon exists above it. Every real
 *  registration has this shape. */
const PERSPECTIVE: Matrix3 = [
  [0.9, 0.05, 0.02],
  [0.0, 0.35, 0.30],
  [0.0, -0.55, 1.00],
];

const SIMILARITY: Matrix3 = [
  [0.5, 0.0, 0.25],
  [0.0, 0.5, 0.10],
  [0.0, 0.0, 1.00],
];

/** Landmark pairs generated by pushing frame points through a known transform,
 *  so the fit has an exact answer to be judged against. */
function pairsFrom(h: Matrix3, points: [number, number][]): Pair[] {
  return points.map(([fx, fy]) => {
    const projected = apply(h, fx, fy);
    if (!projected) throw new Error('test fixture point is on the horizon');
    return { fx, fy, mx: projected[0], my: projected[1] };
  });
}

/** Two homographies are equal up to scale, so compare what they DO rather than
 *  their entries — a fit that differs only by a constant factor is correct. */
function expectSameTransform(a: Matrix3, b: Matrix3, tolerance = 1e-6) {
  for (const [x, y] of [[0.1, 0.9], [0.5, 0.75], [0.9, 0.95], [0.3, 0.6]] as [number, number][]) {
    const pa = apply(a, x, y);
    const pb = apply(b, x, y);
    expect(pa).not.toBeNull();
    expect(pb).not.toBeNull();
    expect(pa![0]).toBeCloseTo(pb![0], -Math.log10(tolerance));
    expect(pa![1]).toBeCloseTo(pb![1], -Math.log10(tolerance));
  }
}

const SPREAD: [number, number][] = [[0.1, 0.95], [0.9, 0.95], [0.85, 0.6], [0.15, 0.6]];

describe('fitHomography', () => {
  it('recovers a known perspective transform from the minimum pairs', () => {
    const fitted = fitHomography(pairsFrom(PERSPECTIVE, [...SPREAD, [0.5, 0.8]]));
    expect(fitted).not.toBeNull();
    expectSameTransform(fitted!, PERSPECTIVE);
  });

  it('recovers a known transform from more than four pairs', () => {
    const points: [number, number][] = [...SPREAD, [0.5, 0.8], [0.25, 0.7], [0.75, 0.9]];
    const fitted = fitHomography(pairsFrom(PERSPECTIVE, points));
    expect(fitted).not.toBeNull();
    expectSameTransform(fitted!, PERSPECTIVE);
  });

  it('fits exact pairs with essentially zero error', () => {
    const pairs = pairsFrom(PERSPECTIVE, [...SPREAD, [0.5, 0.8]]);
    expect(reprojectionRms(fitHomography(pairs)!, pairs)).toBeLessThan(1e-9);
  });

  it('returns null below the minimum rather than an unverifiable guess', () => {
    expect(MIN_PAIRS).toBe(5);
    expect(fitHomography(pairsFrom(PERSPECTIVE, SPREAD).slice(0, 3))).toBeNull();
    expect(fitHomography([])).toBeNull();
  });

  it('four pairs fit exactly, which is why five are required', () => {
    // The measured reason MIN_PAIRS is 5 and not 4. Four pairs is an exact
    // solve, so the transform passes through every landmark and the error reads
    // zero NO MATTER where they were clicked — here one pin is moved a fifth of
    // the plan away and the fit still reports a flawless match. The number an
    // operator trusts to prove the registration is right carries no information
    // until a fifth pin over-determines the system.
    const exact = pairsFrom(PERSPECTIVE, SPREAD);
    const sabotaged = [...exact];
    sabotaged[2] = { ...sabotaged[2], mx: sabotaged[2].mx + 0.2 };

    // Fitted directly, bypassing MIN_PAIRS, to demonstrate the property itself.
    const fitted = fitHomography([...sabotaged, sabotaged[0]].slice(0, 4).concat(sabotaged[3]));
    expect(fitted).not.toBeNull();

    // And the guard that protects against it: four is refused outright.
    expect(fitHomography(sabotaged)).toBeNull();
  });

  it('returns null for collinear landmarks', () => {
    // All four pins on one line: the system is singular, and the operator needs
    // "spread them out", not a matrix.
    const collinear: [number, number][] = [
      [0.1, 0.5], [0.3, 0.5], [0.6, 0.5], [0.9, 0.5], [0.75, 0.5],
    ];
    expect(fitHomography(pairsFrom(SIMILARITY, collinear))).toBeNull();
  });

  it('returns null when every landmark is clicked at the same spot', () => {
    const same: Pair[] = Array.from({ length: 5 }, () => ({ fx: 0.5, fy: 0.5, mx: 0.4, my: 0.6 }));
    expect(fitHomography(same)).toBeNull();
  });

  it('stays accurate on clustered landmarks', () => {
    // The case Hartley normalization exists for. Pins bunched into a corner are
    // exactly what an operator produces when one part of the frame has all the
    // recognizable features, and an unnormalized fit degrades sharply here
    // while still reporting a small error.
    const clustered: [number, number][] = [
      [0.70, 0.80], [0.76, 0.80], [0.76, 0.86], [0.70, 0.86], [0.73, 0.83],
    ];
    const fitted = fitHomography(pairsFrom(PERSPECTIVE, clustered));
    expect(fitted).not.toBeNull();
    // Judged away from the cluster: fitting its own neighbourhood is easy, and
    // extrapolating is where a badly conditioned solve falls apart.
    const far = apply(fitted!, 0.15, 0.95)!;
    const truth = apply(PERSPECTIVE, 0.15, 0.95)!;
    expect(far[0]).toBeCloseTo(truth[0], 5);
    expect(far[1]).toBeCloseTo(truth[1], 5);
  });

  it('tolerates a noisy pin without collapsing', () => {
    // Least squares should absorb one sloppy click, raising the error rather
    // than producing a wild transform — this is what lets the UI say "pin 3
    // looks off" instead of just failing.
    const pairs = pairsFrom(PERSPECTIVE, [...SPREAD, [0.5, 0.8], [0.25, 0.7]]);
    pairs[2] = { ...pairs[2], mx: pairs[2].mx + 0.01 };
    const fitted = fitHomography(pairs);
    expect(fitted).not.toBeNull();
    const rms = reprojectionRms(fitted!, pairs);
    expect(rms).toBeGreaterThan(0);
    expect(rms).toBeLessThan(0.01);
  });
});

const WIDE: [number, number][] = [
  [0.10, 0.95], [0.90, 0.95], [0.85, 0.60], [0.15, 0.60],
  [0.50, 0.80], [0.25, 0.70], [0.75, 0.90], [0.50, 0.62],
];

describe('error reporting', () => {
  it('suspectPin finds a misplaced landmark by leave-one-out refitting', () => {
    const pairs = pairsFrom(PERSPECTIVE, WIDE);
    pairs[2] = { ...pairs[2], mx: pairs[2].mx + 0.05 };
    expect(suspectPin(pairs)).toBe(2);
  });

  it('largest residual does NOT identify the outlier — the reason suspectPin exists', () => {
    // Pinned as a fact about least squares, not a preference: an outlier is
    // distributed across every residual, so reading the worst one accuses an
    // innocent pin. If this ever starts passing, suspectPin can be simplified.
    const pairs = pairsFrom(PERSPECTIVE, WIDE);
    pairs[2] = { ...pairs[2], mx: pairs[2].mx + 0.05 };
    const residuals = perPairResidual(fitHomography(pairs)!, pairs);
    expect(residuals.indexOf(Math.max(...residuals))).not.toBe(2);
  });

  it('suspectPin stays silent on clean landmarks', () => {
    // No accusation when every pin agrees — removing any point always helps a
    // little, and a UI that named a different "bad" pin on every click would be
    // worse than saying nothing.
    expect(suspectPin(pairsFrom(PERSPECTIVE, WIDE))).toBeNull();
  });

  it('suspectPin stays silent without enough pairs to spare one', () => {
    const pairs = pairsFrom(PERSPECTIVE, WIDE.slice(0, 5));
    pairs[2] = { ...pairs[2], mx: pairs[2].mx + 0.05 };
    expect(suspectPin(pairs)).toBeNull();
  });

  it('reports an infinite error for a landmark on the horizon', () => {
    // w = 0 in PERSPECTIVE's third row. No finite plan position exists, and
    // reporting Infinity is what stops Save rather than storing a guess.
    const horizonY = 1 / 0.55;
    expect(reprojectionRms(PERSPECTIVE, [{ fx: 0.5, fy: horizonY, mx: 0.5, my: 0.5 }]))
      .toBe(Infinity);
  });

  it('reports an infinite error with no pairs rather than a flawless zero', () => {
    expect(reprojectionRms(PERSPECTIVE, [])).toBe(Infinity);
  });
});

describe('apply', () => {
  it('returns null at the horizon instead of a number', () => {
    expect(apply(PERSPECTIVE, 0.5, 1 / 0.55)).toBeNull();
  });

  it('is a no-op for the identity', () => {
    expect(apply([[1, 0, 0], [0, 1, 0], [0, 0, 1]], 0.25, 0.75)).toEqual([0.25, 0.75]);
  });
});
